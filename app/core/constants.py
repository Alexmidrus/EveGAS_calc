# ордера в 4–8 опорных цен, и резать их значит прятать реальную ликвидность.
# Отсекаются только явные «стены» — в замере они начинались с ×9.8.
HISTORY_BAND_HIGH_FACTOR = 10.0

# Мягкий порог: строка помечается как неликвидная, но ничего не пересчитывается
