# диапазон уже содержит в себе нормальный спред buy/sell.
HISTORY_WARN_FACTOR = 1.5

# Старше скольких дней история перестаёт считаться опорой. История обновляется
# раз в сутки, и сегодняшнего дня в ней нет никогда, поэтому «вчерашняя» —
# это норма, а не устаревание.
