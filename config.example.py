# Обязательно подставь свой контакт — этого требует API EVE Online.
# Безликие User-Agent попадают под рейт-лимит. В профиле prod шаблонное
# значение считается ошибкой и роняет запуск.
#
# Метку {version} подставляет приложение из app/version.py. Записанный сюда
# руками номер отстанет в тот же день, когда версию поднимут, — на это
# приложение ругается при старте.
ESI_USER_AGENT = "GasLens/{version} (+https://github.com/USER/GasLens; you@example.com)"

# Дата, на которую написан клиент ESI. Фиксирует поведение API.
#
# Дата не должна быть «в будущем»: ESI сравнивает её со своим текущим днём
# по UTC-11 и на 2026-08-14 отвечает 400 «Compatibility date is in the future»
# ещё почти полсуток после наступления 14-го по Москве. Поэтому здесь 13-е —
# проверено живым запросом, ответ 200.
ESI_COMPATIBILITY_DATE = "2026-08-13"

ESI_TIMEOUT = 15.0
ESI_CACHE_TTL = 300  # секунд, меньше нельзя — столько же кэширует сам ESI

HOST = "127.0.0.1"
PORT = 5000

# В профиле prod DEBUG=True — ошибка: отладчик Flask позволяет выполнять
# произвольный код через браузер.
DEBUG = True

# База данных. В dev по умолчанию SQLite-файл в var/ рядом с репозиторием,
# и трогать эту строку не нужно. В prod адрес приходит из переменной
# окружения DATABASE_URL и указывает на MariaDB, MySQL или Postgres.
# DATABASE_URL = "sqlite:///var/evegas_dev.sqlite3"


